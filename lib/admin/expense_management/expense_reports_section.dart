import 'package:flutter/material.dart';

import 'expense_common.dart';
import 'expense_filters.dart';
import 'expense_management_screen.dart';

const Map<String, (String, String)> expenseReportTypes = <String, (String, String)>{
  'daily': ('Daily expense report', 'Totals per expense date'),
  'weekly': ('Weekly expense report', 'Totals per week'),
  'monthly': ('Monthly expense report', 'Totals per month'),
  'annual': ('Annual expense report', 'Totals per year'),
  'department': ('Department expense report', 'Grouped by department and branch'),
  'vendor': ('Vendor expense report', 'Grouped by vendor or beneficiary'),
  'approval': ('Expense approval report', 'Approvers, dates and comments'),
};

class ExpenseReportsSection extends StatefulWidget {
  const ExpenseReportsSection({super.key, required this.ctx});
  final ExpenseModuleContext ctx;
  @override
  State<ExpenseReportsSection> createState() => _ExpenseReportsSectionState();
}

class _ExpenseReportsSectionState extends State<ExpenseReportsSection> {
  ExpenseFilters _filters = ExpenseFilters.thisMonth();
  String? _type;
  String? _busy; // format being exported
  String? _error;
  String? _last;

  Future<void> _export(String format) async {
    if (_type == null) {
      setState(() => _error = 'Select a report type first.');
      return;
    }
    setState(() {
      _busy = format;
      _error = null;
    });
    try {
      final String name = await widget.ctx.api.downloadReport(
        format: format,
        type: _type!,
        filters: _filters.toQuery(includeSearch: false),
      );
      if (!mounted) return;
      setState(() => _last = 'Downloaded $name');
    } catch (e) {
      if (mounted) setState(() => _error = errorText(e));
    } finally {
      if (mounted) setState(() => _busy = null);
    }
  }

  @override
  Widget build(BuildContext context) {
    final Map<String, String> q = _filters.toQuery(includeSearch: false);
    return Column(crossAxisAlignment: CrossAxisAlignment.start, children: <Widget>[
      const Text('1. Choose the period and filters', style: TextStyle(fontWeight: FontWeight.w800, color: expInk)),
      const SizedBox(height: 8),
      ExpenseFilterBar(
        value: _filters,
        categories: widget.ctx.categories,
        vendors: widget.ctx.vendors,
        showSearch: false,
        busy: _busy != null,
        onApply: (ExpenseFilters f) => setState(() => _filters = f),
      ),
      const SizedBox(height: 16),
      const Text('2. Choose a report', style: TextStyle(fontWeight: FontWeight.w800, color: expInk)),
      const SizedBox(height: 8),
      Column(children: <Widget>[
        for (final MapEntry<String, (String, String)> r in expenseReportTypes.entries)
          ListTile(
            key: Key('report-type-${r.key}'),
            dense: true,
            selected: _type == r.key,
            selectedColor: expGreen,
            selectedTileColor: const Color(0xffdbe9e1),
            shape: RoundedRectangleBorder(borderRadius: BorderRadius.circular(7)),
            leading: Icon(_type == r.key ? Icons.radio_button_checked : Icons.radio_button_unchecked),
            title: Text(r.value.$1, style: const TextStyle(fontWeight: FontWeight.w700)),
            subtitle: Text(r.value.$2),
            onTap: () => setState(() => _type = r.key),
          ),
      ]),
      const SizedBox(height: 12),
      ExpenseNotice(
        'Export uses exactly: ${q.entries.map((MapEntry<String, String> e) => '${e.key}=${e.value}').join(', ')}. '
        'Remember to press Apply filters after changing fields. Files are generated by the server and downloaded with your session.',
      ),
      const SizedBox(height: 12),
      Wrap(spacing: 10, runSpacing: 8, children: <Widget>[
        FilledButton.icon(
          key: const Key('report-export-pdf'),
          onPressed: _busy != null ? null : () => _export('pdf'),
          style: FilledButton.styleFrom(backgroundColor: expGreen),
          icon: const Icon(Icons.picture_as_pdf_outlined, size: 18),
          label: Text(_busy == 'pdf' ? 'Preparing PDF...' : 'Export PDF'),
        ),
        OutlinedButton.icon(
          key: const Key('report-export-xlsx'),
          onPressed: _busy != null ? null : () => _export('xlsx'),
          icon: const Icon(Icons.table_view_outlined, size: 18),
          label: Text(_busy == 'xlsx' ? 'Preparing Excel...' : 'Export Excel (.xlsx)'),
        ),
      ]),
      if (_error != null) Padding(padding: const EdgeInsets.only(top: 10), child: ExpenseNotice(_error!, tone: 'error')),
      if (_last != null && _error == null) Padding(padding: const EdgeInsets.only(top: 10), child: ExpenseNotice(_last!)),
    ]);
  }
}
